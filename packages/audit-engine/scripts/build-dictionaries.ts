/**
 * `pnpm --filter @seostudio/audit-engine dictionaries:build` - writes the spelling check's Hunspell dictionaries as
 * modules (`src/dictionaries/<id>.generated.ts`): each dictionary's affix and word files gzipped
 * and base64-encoded, its licence kept in the header. As modules they load the same way in every
 * runtime the crawl runs in (the server, the desktop app's bundled main process, the tests), with no
 * file read at run time.
 *
 * Run it after a dictionary package upgrade. Only dictionaries a permissive (or file-level copyleft)
 * licence lets the app ship are listed: German and Italian are GPL-only and left out.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

/** `packages/seo`. */
const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Each generated dictionary: its id and the package it is read from. */
const DICTIONARIES: readonly { id: string; pkg: string }[] = [
	{ id: "en-us", pkg: "dictionary-en" },
	{ id: "en-gb", pkg: "dictionary-en-gb" },
	{ id: "es", pkg: "dictionary-es" },
	{ id: "fr", pkg: "dictionary-fr" },
	{ id: "nl", pkg: "dictionary-nl" }
];

/**
 * One file of a dictionary package, gzipped and base64-encoded.
 *
 * @param pkg - The package.
 * @param file - The file name.
 * @returns The encoded file.
 */
function encoded(pkg: string, file: string): string {
	const bytes = readFileSync(resolve(packageDir, "node_modules", pkg, file));
	return gzipSync(bytes, { level: 9 }).toString("base64");
}

for (const { id, pkg } of DICTIONARIES) {
	const manifest = JSON.parse(
		readFileSync(resolve(packageDir, "node_modules", pkg, "package.json"), "utf8")
	) as { version: string; license: string };
	const out = [
		`// GENERATED by scripts/build-dictionaries.ts from ${pkg}@${manifest.version} (licence: ${manifest.license}). Do not edit.`,
		"",
		"/** The Hunspell affix and word files, each gzipped and base64-encoded. */",
		"export const dictionary = {",
		`\taff: "${encoded(pkg, "index.aff")}",`,
		`\tdic: "${encoded(pkg, "index.dic")}"`,
		"};",
		""
	].join("\n");
	writeFileSync(resolve(packageDir, "src/dictionaries", `${id}.generated.ts`), out);
}
