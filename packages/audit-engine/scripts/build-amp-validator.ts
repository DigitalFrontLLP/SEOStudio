/**
 * `pnpm --filter @seostudio/audit-engine amp:build` - vendors the official AMP validator
 * (`https://cdn.ampproject.org/v0/validator_wasm.js`, Apache-2.0) as a module,
 * `src/amp-validator.generated.ts`: the script gzipped and base64-encoded, so the AMP check runs
 * the same validator in every runtime the crawl runs in and never downloads code at run time.
 *
 * Run it to take a newer validator (AMP's rules change rarely).
 */
import { Buffer } from "node:buffer";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

/** `packages/seo`. */
const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Where the validator is published. */
const SOURCE = "https://cdn.ampproject.org/v0/validator_wasm.js";

const response = await fetch(SOURCE);
if (!response.ok)
	throw new Error(`The AMP validator could not be downloaded: ${String(response.status)}`);
const script = Buffer.from(await response.arrayBuffer());
const out = [
	`// GENERATED by scripts/build-amp-validator.ts from ${SOURCE} on ${new Date().toISOString().slice(0, 10)} (licence: Apache-2.0, the AMP Project). Do not edit.`,
	"",
	"/** The validator script, gzipped and base64-encoded. */",
	`export const ampValidatorScript = "${gzipSync(script, { level: 9 }).toString("base64")}";`,
	""
].join("\n");
writeFileSync(resolve(packageDir, "src/amp-validator.generated.ts"), out);
